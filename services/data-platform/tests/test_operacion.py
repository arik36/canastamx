def _leer(carpeta, sql, params=()):
    con = duckdb.connect(str(Path(carpeta) / intermedia.ARCHIVO_DE_SIMULACION), read_only=True)
    try:
        return con.execute(sql, list(params)).fetchall()
    finally:
        con.close()


def _corrida(lote="07-2026_Q2", marca="corrida-de-prueba", **kw):
    hora = operacion.ahora()
    c = {"lote": lote, "archivo": f"{lote}.csv", "sha256_entrada": "a" * 64,
         "version_contrato": "1.3.6", "fecha_de_referencia": "2026-08-10",
         "iniciada_en": hora, "terminada_en": hora, "filas_del_archivo": None,
         "filas_leidas": 10, "filas_aceptadas": 9, "filas_en_cuarentena": 1,
         "resultado": "CORRECTA", "frescura_estado": "NO_APLICA", "frescura_dias": 21,
         "detalle": {"ejecucion": marca}}
    c.update(kw)
    return c


def _apartada(huella="b" * 64, motivo="valor_requerido_vacio", compuerta="contrato_por_fila",
              grupo=None):
    return {"motivo": motivo, "nivel": "FILA", "compuerta": compuerta, "huella_fila": huella,
            "grupo": grupo, "fila": {"producto": None, "precio": "25.00"}}


# ── El esquema ──────────────────────────────────────────────────────────────

def test_el_esquema_se_aplica_las_veces_que_sea(contrato, tmp_path):
    """La plataforma lo aplica antes de cada corrida: la segunda vez no puede fallar
    ni duplicar el catálogo."""
    sembrados = re.findall(r"^\s+\('(\w+)',\s*'(?:FILA|LOTE|CORRIDA)'",
                           operacion.SQL.read_text(encoding="utf-8"), flags=re.MULTILINE)
    for _ in range(3):
        con = intermedia._con()
        intermedia.adjuntar_destino(con, contrato, simular=True, carpeta=tmp_path)
        try:
            operacion.aplicar(con, "duckdb")
            assert con.execute("SELECT current_database()").fetchone()[0] == "memory"
        finally:
            con.execute("DETACH destino")
    assert _leer(tmp_path, "SELECT count(*) FROM operacion.motivo")[0][0] == len(sembrados) == 18
    tablas = {t for (t,) in _leer(tmp_path, "SELECT table_name FROM information_schema.tables "
                                            "WHERE table_schema = 'operacion'")}
    assert set(operacion.TABLAS) | {"corrida_vigente", "estado_de_la_plataforma", "deteccion",
                                    "metricas_de_normalizacion"} == tablas


def test_a_postgres_va_el_sql_tal_cual(contrato):
    texto = operacion.SQL.read_text(encoding="utf-8")
    assert texto in operacion.ddl("postgres")


def test_la_traduccion_a_duckdb_se_detiene_si_el_sql_cambia(tmp_path, monkeypatch):
    """Si alguien cambia el SQL y una de las siete diferencias ya no se encuentra, la
    simulación no puede seguir creando otras tablas que la base de verdad."""
    otro = tmp_path / "esquema.sql"
    otro.write_text(operacion.SQL.read_text(encoding="utf-8").replace(
        "GENERATED ALWAYS AS IDENTITY", "GENERATED BY DEFAULT AS IDENTITY"), encoding="utf-8")
    monkeypatch.setattr(operacion, "SQL", otro)
    with pytest.raises(RuntimeError, match="A_DUCKDB"):
        operacion.ddl("duckdb")


# ── Lo que escribe una corrida ─────────────────────────────────────────────

def test_el_lote_se_llama_como_el_archivo_en_los_dos_anios(contrato, tmp_path):
    """La fuente nombra `01-2025_01` en 2025 y `07-2026_Q2` en 2026. El SQL de antes
    sólo aceptaba la segunda: 24 de las 38 corridas no se habrían podido escribir."""
    for i, lote in enumerate(("01-2025_01", "07-2026_Q2")):
        operacion.registrar_corrida(_corrida(lote, f"c{i}"), [], [], [], contrato,
                                    simular=True, carpeta=tmp_path)
    assert _leer(tmp_path, "SELECT lote, quincena FROM operacion.corrida ORDER BY id") == [
        ("01-2025_01", "2025-01-Q1"), ("07-2026_Q2", "2026-07-Q2")]
    with pytest.raises(duckdb.ConstraintException):
        operacion.registrar_corrida(_corrida("L-2026-Q18", "c3"), [], [], [], contrato,
                                    simular=True, carpeta=tmp_path)


def test_una_corrida_detenida_queda_con_sus_pasos_su_cuarentena_y_su_incidente(
        contrato, tmp_path):
    hora = operacion.ahora()
    resumen = {"filas_entrada": 100, "filas_en_cuarentena": 6, "filas_salida": 0,
               "resultado": "DETENIDO", "motivo_lote": "rechazo_mayor_al_umbral",
               "frescura": {"aplica": False, "estado": "AVISA", "dias": 21,
                            "fecha_referencia": "2026-08-10"}}
    traza = {"archivo": "07-2026_Q2.csv", "sha256_entrada": "c" * 64,
             "ejecucion": "esta", "columnas_del_archivo": columnas_del_contrato(contrato),
             "pasos": [operacion.paso("CRUDA", "ingesta", "otra", hora, hora),
                       operacion.paso_de_compuerta("contrato_por_fila", {
                           "filas_entrada": 100, "filas_en_cuarentena": 6, "filas_salida": 94},
                           "esta", hora, hora),
                       operacion.paso_de_promocion(resumen, 94, "esta", hora, hora)]}
    apartadas = [_apartada(f"{i:064d}") for i in range(6)]
    r = operacion.registrar_lote(contrato, "07-2026_Q2", traza, resumen, apartadas,
                                 "2026-08-10", simular=True, carpeta=tmp_path)

    assert _leer(tmp_path, "SELECT resultado, filas_leidas, filas_aceptadas, "
                           "filas_en_cuarentena, frescura_estado FROM operacion.corrida "
                           "WHERE id = ?", [r["id"]]) == [("RECHAZADA", 100, 0, 6, "NO_APLICA")]
    # El paso de la capa cruda era de otra corrida de Dagster: no es de ésta.
    assert _leer(tmp_path, "SELECT orden, nombre, resultado FROM operacion.paso "
                           "WHERE corrida_id = ? ORDER BY orden", [r["id"]]) == [
        (1, "contrato_por_fila", "AVISO"), (2, "promocion_del_lote", "DETENIDO")]
    assert _leer(tmp_path, "SELECT count(*) FROM operacion.cuarentena WHERE corrida_id = ?",
                 [r["id"]])[0][0] == 6
    assert _leer(tmp_path, "SELECT severidad, estado, compuerta, motivo, filas_afectadas "
                           "FROM operacion.incidente WHERE corrida_id = ?", [r["id"]]) == [
        ("INCIDENTE", "ABIERTO", "promocion_del_lote", "rechazo_mayor_al_umbral", 6)]
    assert _leer(tmp_path, "SELECT cumple_h2 FROM operacion.deteccion") == [(True,)]


def test_filas_en_cuarentena_bajo_el_umbral_son_una_corrida_correcta(contrato):
    """CU-02: 3a, 4a y 5a continúan, y el paso 9 la muestra correcta. Con avisos es
    la que trae columnas que el contrato no declara (2a)."""
    resumen = {"filas_entrada": 10, "filas_en_cuarentena": 1, "filas_salida": 9,
               "resultado": "AVISO"}
    columnas = columnas_del_contrato(contrato)
    corrida, _, incidentes = operacion.armar_corrida(
        contrato, "07-2026_Q2", {"columnas_del_archivo": columnas}, resumen, "2026-08-10")
    assert corrida["resultado"] == "CORRECTA" and incidentes == []

    corrida, _, incidentes = operacion.armar_corrida(
        contrato, "07-2026_Q2", {"columnas_del_archivo": [*columnas, "folio"]}, resumen,
        "2026-08-10")
    assert corrida["resultado"] == "CON_AVISOS"
    assert corrida["detalle"]["columnas_extra"] == ["folio"]
    assert incidentes == [{"severidad": "AVISO", "estado": "INFORMATIVO",
                           "compuerta": "deriva_de_esquema", "motivo": "columnas_extra",
                           "filas_afectadas": 0}]


def test_dos_filas_identicas_en_cuarentena_son_dos_ocurrencias(contrato, tmp_path):
    """La misma fila dos veces, idéntica, son dos filas apartadas con la misma huella.
    Con la llave de antes, (corrida, huella, motivo), la segunda se rechazaba."""
    gemelas = [_apartada(), _apartada(), _apartada(motivo="largo_excedido")]
    r = operacion.registrar_corrida(_corrida(filas_aceptadas=8, filas_en_cuarentena=2), [],
                                    gemelas, [], contrato, simular=True, carpeta=tmp_path)
    assert _leer(tmp_path, "SELECT motivo, ocurrencia FROM operacion.cuarentena "
                           "WHERE corrida_id = ? ORDER BY motivo, ocurrencia", [r["id"]]) == [
        ("largo_excedido", 1), ("valor_requerido_vacio", 1), ("valor_requerido_vacio", 2)]
    assert all(n == 0 for _, n in operacion.contar(contrato, True, tmp_path)["comprobaciones"])


def test_si_algo_falla_no_queda_nada_de_la_corrida(contrato, tmp_path):
    """Un motivo que no está en el catálogo: la llave foránea lo rechaza, y la corrida
    no queda a medias, sin su cuarentena."""
    with pytest.raises(duckdb.ConstraintException):
        operacion.registrar_corrida(_corrida(), [], [_apartada(motivo="no_existe")], [],
                                    contrato, simular=True, carpeta=tmp_path)
    assert _leer(tmp_path, "SELECT count(*) FROM operacion.corrida")[0][0] == 0
    # Y un motivo de lote no va a la cuarentena de filas.
    with pytest.raises(duckdb.ConstraintException):
        operacion.registrar_corrida(_corrida(), [], [_apartada(motivo="controles_c1")], [],
                                    contrato, simular=True, carpeta=tmp_path)


def test_agregar_un_paso_lo_pone_al_final_y_mueve_el_termino(contrato, tmp_path):
    hora = operacion.ahora()
    r = operacion.registrar_corrida(
        _corrida(), [operacion.paso("COMPUERTA", "promocion_del_lote", "x", hora, hora, 9, 9)],
        [], [], contrato, simular=True, carpeta=tmp_path)
    fin = operacion.ahora()
    operacion.agregar_paso(r["id"], operacion.paso("INTERMEDIA", "capa_intermedia", "x", fin,
                                                   fin, 9, None, resultado="FALLO"),
                           contrato, simular=True, carpeta=tmp_path, fallida=True)
    assert _leer(tmp_path, "SELECT orden, capa, filas_salida, resultado FROM operacion.paso "
                           "WHERE corrida_id = ? ORDER BY orden", [r["id"]]) == [
        (1, "COMPUERTA", 9, "PASO"), (2, "INTERMEDIA", None, "FALLO")]
    # El instante, no el texto: DuckDB escribe la hora en la zona de la máquina, y a
    # las 18:31 en León ya es el día siguiente en UTC.
    assert _leer(tmp_path, "SELECT resultado, terminada_en = CAST(? AS TIMESTAMPTZ) "
                           "FROM operacion.corrida WHERE id = ?", [fin, r["id"]]) == [
        ("FALLIDA", True)]


def test_contar_encuentra_una_cuenta_que_no_cuadra(contrato, tmp_path):
    r = operacion.registrar_corrida(_corrida(), [], [_apartada()], [], contrato,
                                    simular=True, carpeta=tmp_path)
    assert all(n == 0 for _, n in operacion.contar(contrato, True, tmp_path)["comprobaciones"])
    con = duckdb.connect(str(tmp_path / intermedia.ARCHIVO_DE_SIMULACION))
    con.execute("UPDATE operacion.corrida SET filas_en_cuarentena = 0 WHERE id = ?", [r["id"]])
    con.close()
    malas = [q for q, n in operacion.contar(contrato, True, tmp_path)["comprobaciones"] if n]
    assert len(malas) == 2, malas     # la cuarentena no cuadra, y la suma tampoco


# ── Contra la base de verdad ───────────────────────────────────────────────

@pytest.mark.skipif(os.environ.get("CANASTAMX_PRUEBA_POSTGRES") != "1",
                    reason="contra postgres-analytics: CANASTAMX_PRUEBA_POSTGRES=1 y las "
                           "ANALYTICS_* cargadas")
def test_contra_postgres_una_corrida_completa(contrato):
    """La misma escritura, contra la base de verdad. Usa un lote que no existe en la
    fuente (`12-2099_Q1`) y al final borra lo que escribió, y sólo eso."""
    lote = "12-2099_Q1"

    def ejecutar(sql):
        con = intermedia._con()
        intermedia.adjuntar_destino(con, contrato, simular=False)
        try:
            con.execute(f"CALL postgres_execute('destino', '{intermedia._texto_sql(sql)}')")
        finally:
            con.execute("DETACH destino")

    borrar = (f"DELETE FROM operacion.incidente WHERE corrida_id IN "
              f"(SELECT id FROM operacion.corrida WHERE lote = '{lote}'); "
              f"DELETE FROM operacion.cuarentena WHERE corrida_id IN "
              f"(SELECT id FROM operacion.corrida WHERE lote = '{lote}'); "
              f"DELETE FROM operacion.corrida WHERE lote = '{lote}';")
    antes = operacion.contar(contrato)["tablas"]
    try:
        hora = operacion.ahora()
        r = operacion.registrar_corrida(
            _corrida(lote, filas_en_cuarentena=2, resultado="RECHAZADA", filas_aceptadas=0),
            [operacion.paso("COMPUERTA", "promocion_del_lote", "pg", hora, hora, 8, 0,
                            resultado="DETENIDO")],
            [_apartada(), _apartada()],
            [{"severidad": "INCIDENTE", "estado": "ABIERTO", "compuerta": "promocion_del_lote",
              "motivo": "rechazo_mayor_al_umbral", "filas_afectadas": 2}], contrato)
        assert r["motor"] == "postgres"
        operacion.agregar_paso(r["id"], operacion.paso("INTERMEDIA", "capa_intermedia", "pg",
                                                       hora, operacion.ahora(), 0, 0), contrato)
        despues = operacion.contar(contrato)
        assert despues["tablas"]["corrida"] == antes["corrida"] + 1
        assert despues["tablas"]["cuarentena"] == antes["cuarentena"] + 2
        assert all(n == 0 for _, n in despues["comprobaciones"])
    finally:
        ejecutar(borrar)
    assert operacion.contar(contrato)["tablas"] == antes, "la prueba dejó algo en la base"
